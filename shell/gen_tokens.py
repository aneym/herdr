NAMED_RE = r"(?<![\w-])(?:" + "|".join(NAMED.split()) + r")(?![\w-])"
# Properties that take a color: a named color in their value is a literal.
# Properties that take a color: a named color in their value is a literal. Declarations may span lines.
CSS_COLOR_DECL = re.compile(r"(?:^|[;{\s])((?:background|border|outline|text-decoration|column-rule)[\w-]*|color|fill|stroke|"
                            r"caret-color|accent-color|scrollbar-color|box-shadow|text-shadow)\s*:([^;}]*)", re.I | re.M)
TS_COLOR_PROP = re.compile(r"[\"']?\b(?:color|background\w*|border\w*|outline\w*|fill|stroke|boxShadow|textShadow|caretColor|"
                           r"accentColor|scrollbarColor|textDecorationColor|cursor\w*|selection\w*)[\"']?\s*:\s*[\"'`]([^\"'`]*)[\"'`]")
VAR_USE = re.compile(r"var\(\s*(--shell-[a-z0-9-]+)")
VAR_DEF = re.compile(r"(?:^|[;{\s])(--shell-[a-z0-9-]+)\s*:", re.M)


def strip_comments(text, css):
    """Blank out comments, keeping line numbers. TS line comments need a non-colon before // (not urls)."""
    pattern = r"/\*.*?\*/" if css else r"/\*.*?\*/|(?<![:\\])//[^\n]*"
    return re.sub(pattern, lambda m: re.sub(r"[^\n]", " ", m.group(0)), text, flags=re.S)


def web_lint(generated_css):
    defined = set(VAR_DEF.findall(strip_comments(generated_css, True)))
    problems = []
    for f in sorted(WEB_DIR.rglob("*")):
        if f.suffix not in (".css", ".ts", ".tsx") or f in (CSS_OUT, TS_OUT) or ".test." in f.name:
            continue
        css = f.suffix == ".css"
        text = strip_comments(f.read_text(), css)
        # Only CSS declares variables; a string in TS that looks like one defines nothing.
        local = set(VAR_DEF.findall(text)) if css else set()
        rel = f.relative_to(ROOT)
        found = [(m.start(), m.group(0)) for m in COLOR_LITERAL.finditer(text)]
        decls = CSS_COLOR_DECL if css else TS_COLOR_PROP
        group = 2 if css else 1
        for d in decls.finditer(text):
            # url(...) and quoted strings in a CSS value are names, not colors ("red.svg").
            value = d.group(group) if not css else re.sub(r"url\([^)]*\)|\"[^\"]*\"|'[^']*'",
                                                         lambda m: " " * len(m.group(0)), d.group(group))
            found += [(d.start(group) + m.start(), m.group(0)) for m in re.finditer(NAMED_RE, value, re.I)]
        for pos, lit in sorted(found):
            problems.append(f"{rel}:{text.count(chr(10), 0, pos) + 1}: color literal {lit!r}; use a --shell-* token")
        for m in VAR_USE.finditer(text):
            if m.group(1) not in defined and m.group(1) not in local:
                problems.append(f"{rel}:{text.count(chr(10), 0, m.start()) + 1}: {m.group(1)} is not a generated token")
    return problems


# Text colors and the chrome surfaces they sit on (Alex's parity ask, 2026-10-06: light text at
# least 4.5:1). Dark is not held yet: its mute and faint come from the Mocha-derived palette.
TEXT = ("ink", "mute", "faint", "orch", "lane", "wf", "ok", "warn", "accent", "bad")
SURFACES = ("windowBg", "panel", "sel", "hover", "cap", "field")


def contrast(a, b):
    def lum(v):
        c = [int(hex6(v)[i:i + 2], 16) / 255 for i in (0, 2, 4)]
        c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
        return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
    hi, lo = sorted((lum(a), lum(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def low_contrast(t):
    c = t["color"]["light"]
    return [f"light {fg} {c[fg]} on {bg} {c[bg]} is {contrast(c[fg], c[bg]):.2f}:1, under 4.5:1"
            for fg in TEXT for bg in SURFACES if contrast(c[fg], c[bg]) < 4.5]


def check(t):
    failures = []
    for path, text in outputs(t).items():
        rel = path.relative_to(ROOT)
        if not path.exists() or path.read_text() != text:
            failures.append(f"{rel} is stale; run python3 shell/gen_tokens.py")
        else:
            print(f"PASS {rel} matches shell/tokens.json")
    if not failures:
        eff = mac_effective()
        miss = []
        for mode in ("dark", "light"):
            want = {k: "#" + hex6(v) for k, v in t["color"][mode].items()}
            want["terminalBg"] = "#" + hex6(t["terminal"][mode]["background"])
            want["terminalFg"] = "#" + hex6(t["terminal"][mode]["foreground"])
            for k, v in want.items():
                if eff[mode].get(k) != v:
                    miss.append(f"mac {mode}.{k} = {eff[mode].get(k)} but tokens.json says {v}")
        if miss:
            failures += miss
        else:
            print("PASS mac effective stock colors equal tokens.json (dark, light)")
    low = low_contrast(t)
    if low:
        failures += low
    else:
        print("PASS light text colors are at least 4.5:1 on every light surface")
    lint = web_lint(outputs(t)[CSS_OUT])
    if lint:
        failures += lint
    else:
        print("PASS windows client uses only generated color tokens")
    for f in failures:
        print("FAIL " + f)
    return 1 if failures else 0


def main():
    t = load()
    if "--check" in sys.argv[1:]:
        sys.exit(check(t))
    for path, text in outputs(t).items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
